'use strict';
const assert=require('node:assert/strict');
const api=require('../clue-in-cell.js');
function test(variant){
 const dim=api.sizes[variant],draft=api.blank(variant);
 assert.equal(draft.puzzle.grid.length,dim.height);
 assert.equal(draft.puzzle.grid[0].length,dim.width);
 assert.equal(api.inspect(draft).valid,true);
 assert.equal(api.inspect(draft).publishable,false);
 const across=api.addEntry(draft,{id:'a',clue:'ادامه یافتن',answer:'تداوم',direction:'across',clueCell:[4,5]});
 assert.equal(across.puzzle.grid[4][5].kind,'clue');
 assert.equal(across.puzzle.grid[4][4].answer,'ت');
 assert.equal(across.puzzle.grid[4][0].answer,'م');
 const crossed=api.addEntry(across,{id:'b',clue:'آرزوی دل',answer:'امید',direction:'down',clueCell:[3,2]});
 assert.equal(crossed.puzzle.grid[4][2].answer,'ا');
 assert.equal(api.inspect(crossed).stats.crossings,1);
 assert.equal(api.inspect(crossed).valid,true);
 assert.throws(()=>api.addEntry(across,{id:'b',clue:'غیرهمسان',answer:'بودن',direction:'down',clueCell:[3,2]}),/ناسازگاری حرف تقاطع/);
 assert.throws(()=>api.addEntry(across,{id:'b',clue:'روی سؤال',answer:'گلدان',direction:'down',clueCell:[3,5]}),/برخورد|ناسازگاری/);
 assert.throws(()=>api.addEntry(across,{id:'b',clue:'هم جهت',answer:'تابان',direction:'across',clueCell:[4,6]}),/برخورد|هم‌پوشانی/);
 assert.throws(()=>api.setBlock(crossed,4,2,true),/خانهٔ سیاه|برخورد/);
 const trimmed=api.removeEntry(crossed,'a');
 assert.equal(trimmed.puzzle.grid[4][4].kind,'empty');
 assert.equal(trimmed.puzzle.grid[4][2].answer,'ا');
 assert.throws(()=>api.setBlock(trimmed,0,0,true),/خانهٔ سیاه بدون سؤال/);
 assert.throws(()=>api.finishBlocks(crossed),/سؤال واقعی یا حرف پاسخ/);
 assert.equal(api.inspect(crossed).publishable,false,'Incomplete white cells cannot be disguised as black padding');
 assert.equal(api.validate({...crossed,id:'sample',title:'test',puzzle:{...crossed.puzzle,meta:{status:'published',method:'editor-approved'}}}),false);
 const corrupt=JSON.parse(JSON.stringify(crossed));
 corrupt.puzzle.grid[4][2].answer='ب';
 assert.equal(api.inspect(corrupt).valid,false,'Stored grid must exactly match clue answers');
 const tamper=JSON.parse(JSON.stringify(crossed));
 tamper.puzzle.entries[1].answer='بمید';
 assert.equal(api.inspect(tamper).valid,false);
 console.log('Clue in cell '+variant+': '+dim.width+'×'+dim.height+' draft, crossing, editor, tamper and publication gate passed');
}
test('horizontal');test('vertical');
